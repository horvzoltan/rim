#!/usr/bin/env python3
"""Regenerate the file-type icons: src/file_icons_data.rs and assets/fonts/rim-icons.ttf.

Icons and colours come from nvim-web-devicons (MIT), glyphs from the Nerd Fonts "Symbols Only"
font (MIT). The font is cut down to the glyphs used, so it stays small.

    tools/gen_file_icons.py path/to/SymbolsNerdFont-Regular.ttf

Needs network access (to fetch the devicons tables) and fonttools (`pyftsubset`).
"""

import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

DEVICONS = "https://raw.githubusercontent.com/nvim-tree/nvim-web-devicons/master/lua/"
ROOT = Path(__file__).resolve().parent.parent
# Folder icons (nvim-tree's) and the icons the app uses outside the file table.
EXTRA = {
    "FOLDER": "\ue5ff",
    "FOLDER_OPEN": "\ue5fe",
}
ENTRY = re.compile(r'\["([^"]+)"\]\s*=\s*\{\s*icon\s*=\s*"([^"]+)",\s*color\s*=\s*"#([0-9A-Fa-f]{6})"')


def fetch(path):
    with urllib.request.urlopen(DEVICONS + path) as r:
        return r.read().decode()


def table(kind):
    dark = {k.lower(): (icon, col) for k, icon, col in reversed(ENTRY.findall(fetch(f"nvim-web-devicons/default/{kind}.lua")))}
    light = {k.lower(): col for k, _, col in reversed(ENTRY.findall(fetch(f"nvim-web-devicons/light/{kind}.lua")))}
    return sorted((k, icon, col, light.get(k, col)) for k, (icon, col) in dark.items())


def rust_table(name, rows):
    out = [f"pub static {name}: &[(&str, char, u32, u32)] = &["]
    for key, icon, dark, light in rows:
        out.append(f"    ({json.dumps(key, ensure_ascii=False)}, '\\u{{{ord(icon):x}}}', 0x{dark.upper()}, 0x{light.upper()}),")
    out.append("];")
    return "\n".join(out)


def main():
    font = Path(sys.argv[1])
    by_ext, by_name = table("icons_by_file_extension"), table("icons_by_filename")
    init = fetch("nvim-web-devicons.lua")
    m = re.search(r'default_icon\s*=\s*\{\s*icon\s*=\s*"([^"]+)",\s*color\s*=\s*"#([0-9A-Fa-f]{6})"', init)
    EXTRA["DEFAULT_FILE"] = m.group(1)

    lines = [
        "// Generated by tools/gen_file_icons.py from nvim-web-devicons (MIT). Do not edit.",
        "// (key, glyph, dark-theme colour, light-theme colour); keys are lowercase and sorted.",
        "",
    ]
    for k, ch in EXTRA.items():
        lines.append(f"pub const {k}: char = '\\u{{{ord(ch):x}}}';")
    lines += ["", rust_table("BY_NAME", by_name), "", rust_table("BY_EXT", by_ext), ""]
    (ROOT / "src/file_icons_data.rs").write_text("\n".join(lines))

    glyphs = {icon for rows in (by_ext, by_name) for _, icon, _, _ in rows} | set(EXTRA.values())
    unicodes = ",".join(f"U+{ord(c):04X}" for c in sorted(glyphs))
    out = ROOT / "assets/fonts/rim-icons.ttf"
    subprocess.run(["pyftsubset", str(font), f"--unicodes={unicodes}", f"--output-file={out}", "--no-hinting", "--desubroutinize"], check=True)
    print(f"{len(by_ext)} extensions, {len(by_name)} file names, {len(glyphs)} glyphs -> {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
